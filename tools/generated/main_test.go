package main

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// TestMain lets the test binary double as the generated command.
func TestMain(m *testing.M) {
	if os.Getenv("GENERATED_RUN_MAIN") == "1" {
		main()
		return
	}
	os.Exit(m.Run())
}

func writeModule(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	files["go.mod"] = "module example.com/m\n\ngo 1.22\n"
	for name, content := range files {
		p := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func run(t *testing.T, dir string, args ...string) (string, string, int) {
	t.Helper()
	cmd := exec.Command(os.Args[0], args...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GENERATED_RUN_MAIN=1")
	var out, errb strings.Builder
	cmd.Stdout, cmd.Stderr = &out, &errb
	code := 0
	if err := cmd.Run(); err != nil {
		ee, ok := err.(*exec.ExitError)
		if !ok {
			t.Fatal(err)
		}
		code = ee.ExitCode()
	}
	return out.String(), errb.String(), code
}

func TestListsOnlyGeneratedFiles(t *testing.T) {
	dir := writeModule(t, map[string]string{
		"plain.go":         "package m\n",
		"plain_test.go":    "package m\n",
		"gen.go":           "// Code generated by tool; DO NOT EDIT.\n\npackage m\n",
		"gen_test.go":      "// Code generated by tool; DO NOT EDIT.\n\npackage m\n",
		"sub/pb.go":        "// Code generated by protoc. DO NOT EDIT.\n\npackage sub\n",
		"sub/mention.go":   "package sub\n\n// This file mentions Code generated but is not.\nvar X = 1\n",
		"testdata/skip.go": "// Code generated by tool; DO NOT EDIT.\n\npackage skip\n",
	})
	out, errs, code := run(t, dir, "./...")
	if code != 0 || errs != "" {
		t.Fatalf("code=%d stderr=%q", code, errs)
	}
	want := "example.com/m/gen.go\nexample.com/m/sub/pb.go\n"
	got := out
	// Order follows the directory walk, which is lexical.
	if got != want {
		t.Errorf("stdout = %q, want %q", got, want)
	}
}

func TestNoGeneratedFilesPrintsNothing(t *testing.T) {
	dir := writeModule(t, map[string]string{"a.go": "package m\n"})
	if out, _, code := run(t, dir); code != 0 || out != "" {
		t.Errorf("code=%d out=%q", code, out)
	}
}

func TestGeneratedErrors(t *testing.T) {
	if _, errs, code := run(t, t.TempDir()); code != 2 || !strings.Contains(errs, "generated:") {
		t.Errorf("no go.mod: code=%d err=%q", code, errs)
	}
}
