func TestGenerateWritesOnePagePerCommand(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "commands")
	if err := generate(dir); err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"tfmetrics", "tfmetrics_scan", "tfmetrics_aggregate", "tfmetrics_explain", "tfmetrics_org", "tfmetrics_version"} {
		b, err := os.ReadFile(filepath.Join(dir, name+".md"))
		if err != nil {
			t.Errorf("missing page %s: %v", name, err)
			continue
		}
		if !strings.HasPrefix(string(b), "## "+strings.ReplaceAll(name, "_", " ")) {
			t.Errorf("%s.md starts %q", name, strings.SplitN(string(b), "\n", 2)[0])
		}
		if strings.Contains(string(b), "Auto generated by spf13/cobra") {
			t.Errorf("%s.md has the auto-gen tag", name)
		}
	}
	entries, _ := os.ReadDir(dir)
	if len(entries) != 6 {
		t.Errorf("pages = %d, want 6", len(entries))
	}
	scan, _ := os.ReadFile(filepath.Join(dir, "tfmetrics_scan.md"))
	if !strings.Contains(string(scan), "--sink") || !strings.Contains(string(scan), "[tfmetrics](tfmetrics.md)") {
		t.Errorf("scan page lacks flags or link:\n%s", scan)
	}
	if !strings.HasSuffix(string(scan), configNote) {
		t.Errorf("scan page lacks the config reference link:\n%s", scan)
	}
}

func TestLinkConfig(t *testing.T) {
	dir := t.TempDir()
	with, without := filepath.Join(dir, "a.md"), filepath.Join(dir, "b.md")
	if err := os.WriteFile(with, []byte("  --config string\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(without, []byte("no flags\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := linkConfig(dir); err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(with); !strings.HasSuffix(string(b), configNote) {
		t.Errorf("page with --config not linked: %q", b)
	}
	if b, _ := os.ReadFile(without); string(b) != "no flags\n" {
		t.Errorf("page without --config changed: %q", b)
	}
	// A directory named like a page cannot be read.
	if err := os.Mkdir(filepath.Join(dir, "c.md"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := linkConfig(dir); err == nil {
		t.Error("want error when a page cannot be read")
	}
}

func TestGenerateClearsStalePagesOnly(t *testing.T) {
	dir := t.TempDir()
	stale := filepath.Join(dir, "tfmetrics_removed.md")
	keep := filepath.Join(dir, "README.txt")
	for _, p := range []string{stale, keep} {
		if err := os.WriteFile(p, []byte("x"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	if err := generate(dir); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(stale); err == nil {
		t.Error("stale page not removed")
	}
	if _, err := os.Stat(keep); err != nil {
		t.Error("non-md file removed")
	}
	// Idempotent.
	if err := generate(dir); err != nil {
		t.Fatal(err)
	}
}

func TestGenerateErrors(t *testing.T) {
	f := filepath.Join(t.TempDir(), "file")
	if err := os.WriteFile(f, []byte("x"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := generate(filepath.Join(f, "sub")); err == nil {
		t.Error("want error when dir cannot be created")
	}
	// A directory named like a page cannot be removed as a file when non-empty.
	dir := t.TempDir()
	d := filepath.Join(dir, "x.md")
	if err := os.MkdirAll(filepath.Join(d, "inner"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := generate(dir); err == nil {
		t.Error("want error when a stale page cannot be removed")
	}
}

// TestMain lets the test binary double as the gendocs command.
func TestMain(m *testing.M) {
	if os.Getenv("GENDOCS_RUN_MAIN") == "1" {
		main()
		return
	}
	os.Exit(m.Run())
}

func runMain(t *testing.T, args ...string) (string, int) {
	t.Helper()
	cmd := exec.Command(os.Args[0], args...)
	cmd.Dir = t.TempDir()
	cmd.Env = append(os.Environ(), "GENDOCS_RUN_MAIN=1")
	out, err := cmd.CombinedOutput()
	code := 0
	if ee, ok := err.(*exec.ExitError); ok {
		code = ee.ExitCode()
	} else if err != nil {
		t.Fatal(err)
	}
	return string(out), code
}

func TestMainWritesToArgDirAndDefault(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "out")
	if out, code := runMain(t, dir); code != 0 {
		t.Fatalf("code=%d out=%s", code, out)
	}
	if _, err := os.Stat(filepath.Join(dir, "tfmetrics.md")); err != nil {
		t.Error(err)
	}
	// With no argument it writes docs/reference/commands under the working directory.
	cmd := exec.Command(os.Args[0])
	cmd.Dir = t.TempDir()
	cmd.Env = append(os.Environ(), "GENDOCS_RUN_MAIN=1")
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("%v: %s", err, out)
	}
	if _, err := os.Stat(filepath.Join(cmd.Dir, "docs", "reference", "commands", "tfmetrics_scan.md")); err != nil {
		t.Error(err)
	}
}

func TestMainFailureExitsNonZero(t *testing.T) {
	f := filepath.Join(t.TempDir(), "file")
	if err := os.WriteFile(f, []byte("x"), 0o644); err != nil {
		t.Fatal(err)
	}
	if out, code := runMain(t, filepath.Join(f, "sub")); code != 1 || !strings.Contains(out, "gendocs:") {
		t.Errorf("code=%d out=%s", code, out)
	}
}
