// TestMain lets the test binary double as the doccheck command.
func TestMain(m *testing.M) {
	if os.Getenv("DOCCHECK_RUN_MAIN") == "1" {
		main()
		return
	}
	os.Exit(m.Run())
}

// writeModule writes files into a fresh temp module and chdirs into it.
func writeModule(t *testing.T, files map[string]string) {
	t.Helper()
	dir := t.TempDir()
	files["go.mod"] = "module example.com/m\n\ngo 1.22\n"
	for name, content := range files {
		p := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	t.Chdir(dir)
}

func checkModule(t *testing.T, patterns ...string) []string {
	t.Helper()
	files, err := gofiles.Walk(patterns)
	if err != nil {
		t.Fatal(err)
	}
	return check(files)
}

func TestCheck(t *testing.T) {
	tests := []struct {
		name  string
		files map[string]string
		want  []string
	}{
		{
			"clean",
			map[string]string{"a.go": "// Package m is documented.\npackage m\n\n// F does a thing.\nfunc F() {}\n\n// T is a type.\ntype T struct{}\n\n// M is a method.\nfunc (T) M() {}\n"},
			nil,
		},
		{
			"missing func doc",
			map[string]string{"a.go": "// Package m is documented.\npackage m\n\nfunc F() {}\n"},
			[]string{"a.go:4: F has no doc comment"},
		},
		{
			"missing method doc names the receiver",
			map[string]string{"a.go": "// Package m is documented.\npackage m\n\ntype T struct{}\n\nfunc (t T) Val() {}\n\nfunc (t *T) Ptr() {}\n"},
			[]string{"a.go:6: T.Val has no doc comment", "a.go:8: T.Ptr has no doc comment"},
		},
		{
			"generic receivers",
			map[string]string{"a.go": "// Package m is documented.\npackage m\n\ntype G[A any] struct{}\n\ntype H[A, B any] struct{}\n\nfunc (g G[A]) One() {}\n\nfunc (g *G[A]) Two() {}\n\nfunc (h H[A, B]) Three() {}\n"},
			// Output is sorted as strings, so line 10 sorts before line 8.
			[]string{"a.go:10: G.Two has no doc comment", "a.go:12: H.Three has no doc comment", "a.go:8: G.One has no doc comment"},
		},
		{
			"missing package comment",
			map[string]string{"a.go": "package m\n\n// F is documented.\nfunc F() {}\n"},
			[]string{".: package has no package comment"},
		},
		{
			"package comment in any file of the package counts",
			map[string]string{
				"a.go": "package m\n\n// F is documented.\nfunc F() {}\n",
				"b.go": "// Package m is documented here.\npackage m\n",
			},
			nil,
		},
		{
			"per directory package comments",
			map[string]string{
				"a.go":     "// Package m is documented.\npackage m\n",
				"sub/b.go": "package sub\n",
			},
			[]string{"sub: package has no package comment"},
		},
		{
			"test files skipped",
			map[string]string{
				"a.go":      "// Package m is documented.\npackage m\n",
				"a_test.go": "package m\n\nfunc TestX() {}\n",
			},
			nil,
		},
		{
			"generated files skipped",
			map[string]string{
				"a.go":   "// Package m is documented.\npackage m\n",
				"gen.go": "// Code generated by x; DO NOT EDIT.\n\npackage m\n\nfunc Undocumented() {}\n",
			},
			nil,
		},
		{
			"only test files: no package comment demanded",
			map[string]string{"a_test.go": "package m\n"},
			nil,
		},
		{
			"non-function declarations ignored",
			map[string]string{"a.go": "// Package m is documented.\npackage m\n\nvar X = 1\n\ntype T int\n\nconst C = 2\n"},
			nil,
		},
		{
			"sorted output",
			map[string]string{"a.go": "// Package m is documented.\npackage m\n\nfunc Z() {}\n\nfunc A() {}\n"},
			[]string{"a.go:4: Z has no doc comment", "a.go:6: A has no doc comment"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			writeModule(t, tt.files)
			got := checkModule(t, "./...")
			if strings.Join(got, "\n") != strings.Join(tt.want, "\n") {
				t.Errorf("got:\n%s\nwant:\n%s", strings.Join(got, "\n"), strings.Join(tt.want, "\n"))
			}
		})
	}
}

func TestRecvName(t *testing.T) {
	writeModule(t, map[string]string{"a.go": "// Package m is documented.\npackage m\n\ntype T struct{}\n\nfunc (T) A() {}\n"})
	files, err := gofiles.Walk(nil)
	if err != nil {
		t.Fatal(err)
	}
	if len(files) != 1 {
		t.Fatalf("files = %d", len(files))
	}
	if got := recvName(nil); got != "?" {
		t.Errorf("recvName(nil) = %q, want ?", got)
	}
}

// runMain runs the doccheck command in dir and returns combined output and the exit code.
func runMain(t *testing.T, dir string, args ...string) (stdout, stderr string, code int) {
	t.Helper()
	cmd := exec.Command(os.Args[0], args...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "DOCCHECK_RUN_MAIN=1")
	var out, errb strings.Builder
	cmd.Stdout, cmd.Stderr = &out, &errb
	err := cmd.Run()
	if ee, ok := err.(*exec.ExitError); ok {
		code = ee.ExitCode()
	} else if err != nil {
		t.Fatal(err)
	}
	return out.String(), errb.String(), code
}

func TestMainExitCodes(t *testing.T) {
	writeModule(t, map[string]string{"a.go": "// Package m is documented.\npackage m\n\nfunc F() {}\n"})
	dir, _ := os.Getwd()
	out, errs, code := runMain(t, dir, "./...")
	if code != 1 || !strings.Contains(out, "a.go:4: F has no doc comment") || !strings.Contains(errs, "1 missing doc comments") {
		t.Errorf("failing module: code=%d out=%q err=%q", code, out, errs)
	}

	writeModule(t, map[string]string{"a.go": "// Package m is documented.\npackage m\n\n// F is documented.\nfunc F() {}\n"})
	dir, _ = os.Getwd()
	if out, errs, code := runMain(t, dir, "./..."); code != 0 || out != "" || errs != "" {
		t.Errorf("clean module: code=%d out=%q err=%q", code, out, errs)
	}

	empty := t.TempDir()
	if _, errs, code := runMain(t, empty); code != 2 || !strings.Contains(errs, "doccheck:") {
		t.Errorf("no go.mod: code=%d err=%q", code, errs)
	}
}
