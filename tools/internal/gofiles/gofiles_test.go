package gofiles

import (
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

const genHeader = "// Code generated by hand; DO NOT EDIT.\n\npackage x\n"

// makeModule writes a small module under a temp dir and chdirs into it.
func makeModule(t *testing.T) {
	t.Helper()
	dir := t.TempDir()
	files := map[string]string{
		"go.mod":                "module example.com/mod\n\ngo 1.22\n",
		"a.go":                  "// Package mod is a.\npackage mod\n",
		"a_test.go":             "package mod\n",
		"gen.go":                genHeader,
		"sub/b.go":              "package sub\n",
		"sub/deep/c.go":         "package deep\n",
		"testdata/skip.go":      "package skip\n",
		"sub/testdata/skip2.go": "package skip\n",
		"vendor/v.go":           "package v\n",
		".hidden/h.go":          "package h\n",
		"_underscore/u.go":      "package u\n",
		"sub/notgo.txt":         "x",
		"other/o.go":            "package other\n",
	}
	for name, content := range files {
		p := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	t.Chdir(dir)
}

func paths(files []File) []string {
	var out []string
	for _, f := range files {
		out = append(out, f.Path)
	}
	sort.Strings(out)
	return out
}

func TestModulePath(t *testing.T) {
	dir := t.TempDir()
	tests := []struct {
		name, gomod, want string
		wantErr           bool
	}{
		{"simple", "module example.com/m\n", "example.com/m", false},
		{"indented with comment lines", "// c\n\n  module   example.com/m  \ngo 1.22\n", "example.com/m", false},
		{"no module line", "go 1.22\n", "", false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			d := filepath.Join(dir, strings.ReplaceAll(tt.name, " ", "_"))
			if err := os.MkdirAll(d, 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(filepath.Join(d, "go.mod"), []byte(tt.gomod), 0o644); err != nil {
				t.Fatal(err)
			}
			got, err := ModulePath(d)
			if (err != nil) != tt.wantErr || got != tt.want {
				t.Errorf("ModulePath = %q, %v; want %q", got, err, tt.want)
			}
		})
	}
	if _, err := ModulePath(filepath.Join(dir, "missing")); err == nil {
		t.Error("missing go.mod should error")
	}
}

func TestWalk(t *testing.T) {
	makeModule(t)
	tests := []struct {
		name     string
		patterns []string
		want     []string
	}{
		{"default is recursive", nil, []string{"a.go", "a_test.go", "gen.go", "other/o.go", "sub/b.go", "sub/deep/c.go"}},
		{"explicit recursive", []string{"./..."}, []string{"a.go", "a_test.go", "gen.go", "other/o.go", "sub/b.go", "sub/deep/c.go"}},
		{"dir recursive", []string{"sub/..."}, []string{"sub/b.go", "sub/deep/c.go"}},
		{"non-recursive root", []string{"."}, []string{"a.go", "a_test.go", "gen.go"}},
		{"non-recursive subdir", []string{"sub"}, []string{"sub/b.go"}},
		{"two patterns dedupe", []string{"sub", "sub/..."}, []string{"sub/b.go", "sub/deep/c.go"}},
		{"explicit testdata dir is walked", []string{"testdata"}, []string{"testdata/skip.go"}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			files, err := Walk(tt.patterns)
			if err != nil {
				t.Fatal(err)
			}
			got := paths(files)
			if strings.Join(got, ",") != strings.Join(tt.want, ",") {
				t.Errorf("got %v\nwant %v", got, tt.want)
			}
		})
	}
}

func TestWalkFileFields(t *testing.T) {
	makeModule(t)
	files, err := Walk([]string{"."})
	if err != nil {
		t.Fatal(err)
	}
	by := map[string]File{}
	for _, f := range files {
		by[f.Path] = f
	}
	a := by["a.go"]
	if a.ImportPath != "example.com/mod/a.go" || a.Generated || a.Test || a.AST == nil || a.Fset == nil || a.AST.Doc == nil {
		t.Errorf("a.go = %+v", a)
	}
	if !by["a_test.go"].Test || by["a_test.go"].Generated {
		t.Errorf("a_test.go = %+v", by["a_test.go"])
	}
	if !by["gen.go"].Generated || by["gen.go"].Test {
		t.Errorf("gen.go = %+v", by["gen.go"])
	}
}

func TestWalkErrors(t *testing.T) {
	t.Run("no go.mod", func(t *testing.T) {
		t.Chdir(t.TempDir())
		if _, err := Walk(nil); err == nil {
			t.Error("want error without go.mod")
		}
	})
	t.Run("syntax error", func(t *testing.T) {
		makeModule(t)
		if err := os.WriteFile("bad.go", []byte("package"), 0o644); err != nil {
			t.Fatal(err)
		}
		if _, err := Walk(nil); err == nil {
			t.Error("want parse error")
		}
	})
	t.Run("missing pattern dir", func(t *testing.T) {
		makeModule(t)
		if _, err := Walk([]string{"nope/..."}); err == nil {
			t.Error("want error for a missing directory")
		}
	})
}
